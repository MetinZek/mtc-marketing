/**
 * Copies the handful of Solar icons the site uses out of the Iconify icon
 * set into src/components/ui/solar-icons.ts, so pages ship a few hundred
 * bytes of SVG instead of the whole set.
 *
 *   node scripts/build-icons.mjs
 *
 * Solar is by 480 Design, licensed CC BY 4.0. Add a name to ICONS and run
 * the script again to make another icon available to <Icon>.
 */

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getIconData, iconToSVG } from "@iconify/utils";
import solar from "@iconify-json/solar/icons.json" with { type: "json" };

/** Site name → Solar icon name. */
const ICONS = {
  "arrow-right": "arrow-right-linear",
  "arrow-left": "arrow-left-linear",
  "arrow-up": "arrow-up-linear",
  "arrow-up-right": "arrow-right-up-linear",
  "chevron-right": "alt-arrow-right-linear",
  "chevron-left": "alt-arrow-left-linear",
  copy: "copy-linear",
  check: "check-read-linear",
  "check-circle": "check-circle-linear",
  plus: "add-circle-linear",
  close: "close-circle-linear",
  mail: "letter-linear",
  phone: "phone-linear",
  menu: "hamburger-menu-linear",
  play: "play-linear",
  pause: "pause-linear",
  globe: "global-linear",
  clock: "clock-circle-linear",
  pin: "map-point-linear",
  grid: "widget-linear",
  list: "list-linear",
  // The base shape of the footer's "hey!" speech-bubble sticker.
  "chat-round": "chat-round-bold",
};

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out = path.join(root, "src/components/ui/solar-icons.ts");

const entries = Object.entries(ICONS).map(([name, solarName]) => {
  const data = getIconData(solar, solarName);
  if (!data) throw new Error(`Solar has no icon named "${solarName}"`);
  const { body } = iconToSVG(data);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`;
});

const source = `/**
 * Generated by scripts/build-icons.mjs from the Solar icon set (480 Design,
 * CC BY 4.0, https://github.com/480-Design/Solar-Icon-Set) as published by
 * Iconify. Do not edit by hand: change ICONS in the script and run it again.
 */
export const SOLAR_ICONS = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof SOLAR_ICONS;
`;

await fs.writeFile(out, source);
console.log(`Wrote ${entries.length} icons to ${path.relative(root, out)}`);
